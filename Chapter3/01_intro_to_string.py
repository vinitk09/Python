#String is a sequence of characters. It is a data type in Python that is used to represent text. Strings are enclosed in either single quotes (' ') or double quotes (" "). It is immutable, meaning that once a string is created, it cannot be changed. However, you can create a new string based on the original string.

#Strings can be concatenated using the + operator, and they can be repeated using the * operator. You can also access individual characters in a string using indexing, and you can extract substrings using slicing.


str = "Hello, World!"

print(str[0:3]) # Output: Hel

print(str[:4])

print(str[-1:])

print(str[1:8:2])